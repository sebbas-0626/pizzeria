-- =====================================================================================
-- V1  Base schema (enteros)
-- =====================================================================================

CREATE TABLE users (
    id            BIGINT       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    first_name    VARCHAR(100) NOT NULL,
    last_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    role          VARCHAR(20)  NOT NULL DEFAULT 'CLIENTE',
    enabled       BOOLEAN      NOT NULL DEFAULT true,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT chk_users_role CHECK (role IN ('CLIENTE', 'COOK', 'ADMIN'))
);

CREATE INDEX ix_users_role ON users (role);

CREATE TABLE addresses (
    id           BIGINT       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT       NOT NULL,
    alias        VARCHAR(50)  NOT NULL,
    street       VARCHAR(200) NOT NULL,
    city         VARCHAR(100) NOT NULL,
    neighborhood VARCHAR(100),
    reference    TEXT,
    is_default   BOOLEAN      NOT NULL DEFAULT false,
    created_at   TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX ix_addresses_user ON addresses (user_id);

CREATE TABLE categories (
    id          BIGINT       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    active      BOOLEAN      NOT NULL DEFAULT true,
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id           BIGINT        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    category_id  BIGINT        NOT NULL,
    name         VARCHAR(150)  NOT NULL,
    description  TEXT,
    price        DECIMAL(10,2) NOT NULL,
    image_url    VARCHAR(500),
    available    BOOLEAN       NOT NULL DEFAULT true,
    created_at   TIMESTAMP     NOT NULL DEFAULT now(),
    updated_at   TIMESTAMP     NOT NULL DEFAULT now(),

    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT
);

CREATE INDEX ix_products_category ON products (category_id);
CREATE INDEX ix_products_name ON products (name);
CREATE INDEX ix_products_available ON products (available);

CREATE TABLE ingredients (
    id          BIGINT       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    available   BOOLEAN      NOT NULL DEFAULT true,
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE product_ingredients (
    product_id     BIGINT        NOT NULL,
    ingredient_id  BIGINT        NOT NULL,
    quantity       DECIMAL(10,2),

    CONSTRAINT pk_product_ingredients PRIMARY KEY (product_id, ingredient_id),
    CONSTRAINT fk_pi_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_pi_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients (id) ON DELETE RESTRICT
);

CREATE TABLE orders (
    id            BIGINT        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT        NOT NULL,
    address_id    BIGINT        NOT NULL,
    status        VARCHAR(20)   NOT NULL DEFAULT 'RECEIVED',
    payment_method VARCHAR(20)  NOT NULL,
    subtotal      DECIMAL(10,2) NOT NULL,
    delivery_fee  DECIMAL(10,2) NOT NULL DEFAULT 0,
    total         DECIMAL(10,2) NOT NULL,
    notes         TEXT,
    created_at    TIMESTAMP     NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP     NOT NULL DEFAULT now(),

    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_address FOREIGN KEY (address_id) REFERENCES addresses (id) ON DELETE RESTRICT,
    CONSTRAINT chk_orders_status CHECK (status IN ('RECEIVED','IN_PREPARATION','READY','ON_THE_WAY','DELIVERED','CANCELLED')),
    CONSTRAINT chk_orders_payment_method CHECK (payment_method IN ('CASH','CARD_ON_DELIVERY','BANK_TRANSFER'))
);

CREATE INDEX ix_orders_user ON orders (user_id);
CREATE INDEX ix_orders_status ON orders (status);
CREATE INDEX ix_orders_created_at ON orders (created_at);

CREATE TABLE order_items (
    id         BIGINT        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id   BIGINT        NOT NULL,
    product_id BIGINT        NOT NULL,
    quantity   INTEGER       NOT NULL,
    unit_price DECIMAL(10,2) NOT NULL,
    subtotal   DECIMAL(10,2) NOT NULL,
    notes      TEXT,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT
);

CREATE INDEX ix_order_items_order ON order_items (order_id);
CREATE INDEX ix_order_items_product ON order_items (product_id);

CREATE TABLE order_status_history (
    id              BIGINT      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id        BIGINT      NOT NULL,
    previous_status VARCHAR(20),
    new_status      VARCHAR(20) NOT NULL,
    changed_by      BIGINT,
    created_at      TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT fk_osh_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_osh_user FOREIGN KEY (changed_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_osh_previous CHECK (previous_status IS NULL OR previous_status IN ('RECEIVED','IN_PREPARATION','READY','ON_THE_WAY','DELIVERED','CANCELLED')),
    CONSTRAINT chk_osh_new CHECK (new_status IN ('RECEIVED','IN_PREPARATION','READY','ON_THE_WAY','DELIVERED','CANCELLED'))
);

CREATE INDEX ix_osh_order ON order_status_history (order_id);
CREATE INDEX ix_osh_created_at ON order_status_history (created_at);
